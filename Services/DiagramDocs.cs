using System;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace AntigravitySidebar.Services
{
    /// <summary>Turns a diagram into a Markdown section for docs/ARCHITECTURE.md and merges it into an existing file without touching anything else in it.</summary>
    public static class DiagramDocs
    {
        public const string RelativePath = "docs/ARCHITECTURE.md";
        public const string StartMarker = "<!-- levity:diagram:start -->";
        public const string EndMarker = "<!-- levity:diagram:end -->";

        /// <summary>The generated section, between markers so a later run can replace exactly this part.</summary>
        public static string Render(DiagramResult r)
        {
            var sb = new StringBuilder();
            sb.AppendLine(StartMarker);
            sb.AppendLine("## Architecture");
            sb.AppendLine();
            if (r.Graph.Overview.Length > 0) { sb.AppendLine(EscapeMarkdown(r.Graph.Overview)); sb.AppendLine(); }
            sb.AppendLine("```mermaid");
            sb.Append(r.Compiled.Mermaid.TrimEnd());
            sb.AppendLine();
            sb.AppendLine("```");
            sb.AppendLine();
            sb.AppendLine("Solid arrows are backed by a reference in the code. Dashed arrows are inferred: plausible, but no reference was found in the files that were read.");
            sb.AppendLine();
            sb.AppendLine("### Components");
            sb.AppendLine();
            foreach (var n in r.Compiled.Nodes)
            {
                sb.Append("- **").Append(EscapeMarkdown(n.Label)).Append("**");
                if (n.Path != null) sb.Append(": [`").Append(n.Path).Append("`](../").Append(Uri.EscapeDataString(n.Path).Replace("%2F", "/")).Append(')');
                sb.AppendLine();
            }
            sb.AppendLine();
            string commit = r.Head != null ? " from commit `" + r.Head.Substring(0, Math.Min(7, r.Head.Length)) + "`" : "";
            sb.AppendLine($"_Generated by Levity on {r.GeneratedUtc:yyyy-MM-dd}{commit}. Re-run it to refresh this section; text outside the markers is never touched._");
            sb.Append(EndMarker);
            return sb.ToString();
        }

        /// <summary>
        /// Puts <paramref name="section"/> into <paramref name="existing"/>: replaces a previous generated section, or appends a new one.
        /// A null or empty file becomes a new document.
        /// </summary>
        public static string Merge(string? existing, string section)
        {
            string newline = existing != null && existing.Contains("\r\n") ? "\r\n" : "\n";
            string body = section.Replace("\r\n", "\n").Replace("\n", newline);

            if (string.IsNullOrWhiteSpace(existing))
                return "# Architecture" + newline + newline + body + newline;

            int start = existing.IndexOf(StartMarker, StringComparison.Ordinal);
            int end = start >= 0 ? existing.IndexOf(EndMarker, start, StringComparison.Ordinal) : -1;
            if (start >= 0 && end > start)
                return existing.Substring(0, start) + body + existing.Substring(end + EndMarker.Length);

            return existing.TrimEnd() + newline + newline + body + newline;
        }

        /// <summary>Text that is shown as plain text in Markdown: no HTML, no emphasis, no links, no headings.</summary>
        public static string EscapeMarkdown(string text)
        {
            string clean = DiagramText.Normalize(text);
            var sb = new StringBuilder(clean.Length + 8);
            foreach (char c in clean)
            {
                if (c == '<') sb.Append("&lt;");
                else if (c == '>') sb.Append("&gt;");
                else if (c == '&') sb.Append("&amp;");
                else if ("\\`*_{}[]()#+-.!|~".IndexOf(c) >= 0) sb.Append('\\').Append(c);
                else sb.Append(c);
            }
            return sb.ToString();
        }
    }

    /// <summary>The message the sidebar and the phone receive. Nodes are referred to by number; only the PC ever turns a number into a path.</summary>
    public static class DiagramPayload
    {
        public static object Build(DiagramResult r)
        {
            var index = r.Compiled.Nodes.ToDictionary(n => n.Id, n => n.Index);
            return new
            {
                type = "diagram",
                path = r.Root,
                overview = r.Graph.Overview,
                groups = r.Graph.Groups.Select(g => new { id = g.Id, label = g.Label }),
                nodes = r.Compiled.Nodes.Select(n => new
                {
                    i = n.Index,
                    label = n.Label,
                    group = n.Group,
                    path = n.Path,
                    shape = r.Graph.Nodes.First(x => x.Id == n.Id).Shape,
                }),
                edges = r.Graph.Edges.Select(e => new
                {
                    from = index[e.From],
                    to = index[e.To],
                    label = e.Label,
                    support = e.Support.ToString().ToLowerInvariant(),
                    evidence = e.EvidencePath,
                }),
                mermaid = r.Compiled.Mermaid,
                generatedUtc = r.GeneratedUtc,
                head = r.Head,
                stale = r.Stale,
                stats = r.Stats,
                notes = r.Notes,
                tokens = r.Tokens,
            };
        }
    }
}
